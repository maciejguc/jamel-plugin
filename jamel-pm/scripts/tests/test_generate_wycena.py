@pytest.mark.parametrize("name", ["range", "fixed"])
def test_matches_golden_render(name: str):
    golden_path = GOLDEN_DIR / f"{name}-golden.xlsx"
    assert golden_path.exists(), "run regenerate_golden.py and review the output first"

    generated = openpyxl.load_workbook(BytesIO(generate_from_payload(load_payload(name))))
    golden = openpyxl.load_workbook(golden_path)

    assert generated.sheetnames == golden.sheetnames
    for sheet in golden.sheetnames:
        gws, ows = generated[sheet], golden[sheet]
        assert gws.max_row == ows.max_row and gws.max_column == ows.max_column
        assert sorted(str(r) for r in gws.merged_cells.ranges) == \
               sorted(str(r) for r in ows.merged_cells.ranges)
        for grow, orow in zip(gws.iter_rows(), ows.iter_rows()):
            for gcell, ocell in zip(grow, orow):
                coord = f"{sheet}!{gcell.coordinate}"
                assert gcell.value == ocell.value, coord
                assert gcell.number_format == ocell.number_format, coord
                gfill = gcell.fill.fgColor.rgb if gcell.fill.fill_type else None
                ofill = ocell.fill.fgColor.rgb if ocell.fill.fill_type else None
                assert gfill == ofill, coord


