def test_kinds_and_totals():
    payload = {
        "meta": _meta(),
        "pricing_mode": "range",
        "line_items": [
            {"stage": "s", "title": "hourly", "role": "Tester", "hours_min": 10, "hours_max": 20},
            {"stage": "s", "title": "ryczałt", "role": "Copywriter", "kind": "fixed",
             "amount_min": 4500, "amount_max": 7000},
            {"stage": "s", "title": "rabat", "role": "Project Manager", "kind": "fixed", "amount": -1000},
            {"stage": "s", "title": "w cenie", "role": "Project Manager", "kind": "included", "hours": 2},
        ],
    }
    items = assemble_line_items(payload)
    by_title = {li.title: li for li in items}
    assert by_title["hourly"].total_min == Decimal("1800")
    assert by_title["hourly"].total_max == Decimal("3600")
    assert by_title["ryczałt"].total_min == Decimal("4500")
    assert by_title["rabat"].total_min == by_title["rabat"].total_max == Decimal("-1000")
    assert by_title["w cenie"].total_min == Decimal("0")
    assert sum_totals(items) == (Decimal("5300"), Decimal("9600"))


def test_invalid_items_raise():
    base = {"meta": _meta(), "pricing_mode": "fixed"}
    with pytest.raises(ValueError, match="kind"):
        assemble_line_items({**base, "line_items": [
            {"stage": "s", "title": "x", "role": "Tester", "kind": "nope"}]})
    with pytest.raises(ValueError, match="hours"):
        assemble_line_items({**base, "line_items": [
            {"stage": "s", "title": "x", "role": "Tester"}]})
    with pytest.raises(ValueError, match="amount"):
        assemble_line_items({**base, "line_items": [
            {"stage": "s", "title": "x", "role": "Tester", "kind": "fixed"}]})
    with pytest.raises(ValueError, match="pricing_mode"):
        generate_from_payload({"meta": _meta(), "line_items": []})


