RANGE_HEADERS = ["Etap", "Opis", "Zadanie Wykonawcy", "Rola", "RH (min)", "RH (max)",
                 "Stawka", "Kwota całkowita netto (min)", "Kwota całkowita netto (max)"]
FIXED_HEADERS = ["Etap", "Opis", "Zadanie Wykonawcy", "Rola", "RH", "Stawka",
                 "Kwota całkowita netto"]


def _cells(ws):
    return [c for row in ws.iter_rows() for c in row if c.value is not None]


def test_range_structure():
    wb = render(load_payload("range"))
    assert wb.sheetnames == ["Wycena", "Elementy dodatkowe"]
    ws = wb["Wycena"]

    assert [ws.cell(row=5, column=c).value for c in range(2, 11)] == RANGE_HEADERS
    assert ws["C1"].value == "Wycena wdrożenia serwisu\ndla Sprint"
    assert ws.sheet_view.showGridLines is False

    payload = load_payload("range")
    hourly = [i for i in payload["line_items"] if i.get("kind", "hourly") == "hourly"]
    formulas_i = [c.value for c in _cells(ws) if isinstance(c.value, str) and c.value.startswith("=F") and "*H" in c.value]
    formulas_j = [c.value for c in _cells(ws) if isinstance(c.value, str) and c.value.startswith("=G") and "*H" in c.value]
    assert len(formulas_i) == len(formulas_j) == len(hourly)

    # Ryczałt row: '-' markers + literal amounts.
    ryczalt_row = next(r for r in range(6, ws.max_row) if ws.cell(row=r, column=3).value == "Copywriting")
    assert [ws.cell(row=ryczalt_row, column=c).value for c in (6, 7, 8, 9, 10)] == ["-", "-", "-", 4500, 7000]

    # Included row: hours visible, zero rate and amounts.
    incl_row = next(r for r in range(6, ws.max_row) if ws.cell(row=r, column=3).value == "Szkolenie")
    assert [ws.cell(row=incl_row, column=c).value for c in (6, 7, 8, 9, 10)] == [2, 2, 0, 0, 0]

    # SUMA: labels + contiguous =SUM over exactly the item rows.
    sum_row = next(r for r in range(6, ws.max_row + 1) if ws.cell(row=r, column=9).value == "SUMA (min)")
    assert ws.cell(row=sum_row, column=10).value == "SUMA (max)"
    item_rows = [r for r in range(6, ws.max_row) if isinstance(ws.cell(row=r, column=2).value, str)
                 and "." in str(ws.cell(row=r, column=2).value)]
    assert ws.cell(row=sum_row + 1, column=9).value == f"=SUM(I{item_rows[0]}:I{item_rows[-1]})"
    assert ws.cell(row=sum_row + 1, column=10).value == f"=SUM(J{item_rows[0]}:J{item_rows[-1]})"

    # Hours/rates are typed numbers, not strings; item numbers are text.
    first_item = item_rows[0]
    assert isinstance(ws.cell(row=first_item, column=6).value, (int, float))
    assert isinstance(ws.cell(row=first_item, column=8).value, (int, float))
    assert ws.cell(row=first_item, column=2).value == "1.1"

    # No unsubstituted placeholders anywhere.
    for sheet in wb.sheetnames:
        assert not any("{{" in str(c.value) for c in _cells(wb[sheet]))

    # Coral banner + coral SUMA values (spot style checks).
    banner_row = next(r for r in range(6, ws.max_row) if ws.cell(row=r, column=2).value == "Programowanie")
    assert ws.cell(row=banner_row, column=2).font.color.rgb == "FFFF818D"
    assert ws.cell(row=sum_row + 1, column=9).fill.fgColor.rgb == "FFFF818D"


def test_fixed_structure():
    payload = load_payload("fixed")
    wb = render(payload)
    assert wb.sheetnames == ["Wycena"]  # no additional_items -> single sheet
    ws = wb["Wycena"]

    assert [ws.cell(row=5, column=c).value for c in range(2, 9)] == FIXED_HEADERS

    hourly = [i for i in payload["line_items"] if i.get("kind", "hourly") == "hourly"]
    formulas = [c.value for c in _cells(ws) if isinstance(c.value, str) and c.value.startswith("=F") and "*G" in c.value]
    assert len(formulas) == len(hourly)

    rabat_row = next(r for r in range(6, ws.max_row) if ws.cell(row=r, column=3).value == "Rabat")
    assert ws.cell(row=rabat_row, column=8).value == -1000

    incl_row = next(r for r in range(6, ws.max_row) if ws.cell(row=r, column=3).value == "Szkolenie")
    assert ws.cell(row=incl_row, column=6).value == "W cenie"
    assert ws.cell(row=incl_row, column=8).value is None

    sum_row = next(r for r in range(6, ws.max_row + 1) if ws.cell(row=r, column=7).value == "SUMA")
    item_rows = [r for r in range(6, ws.max_row) if isinstance(ws.cell(row=r, column=2).value, str)
                 and "." in str(ws.cell(row=r, column=2).value)]
    assert ws.cell(row=sum_row, column=8).value == f"=SUM(H{item_rows[0]}:H{item_rows[-1]})"
    assert ws.cell(row=sum_row, column=8).fill.fgColor.rgb == "FFFF818D"


def test_band_verification_matches_formula_semantics():
    """sum_totals must equal what the sheet formulas would evaluate to."""
    payload = load_payload("range")
    total_min, total_max = sum_totals(assemble_line_items(payload))
    expected_min = expected_max = Decimal("0")
    for item in payload["line_items"]:
        kind = item.get("kind", "hourly")
        if kind == "hourly":
            rate = ROLE_RATES[item["role"]]
            expected_min += Decimal(str(item["hours_min"])) * rate
            expected_max += Decimal(str(item["hours_max"])) * rate
        elif kind == "fixed":
            expected_min += Decimal(str(item.get("amount_min", item.get("amount"))))
            expected_max += Decimal(str(item.get("amount_max", item.get("amount"))))
    assert (total_min, total_max) == (expected_min, expected_max)


